const unsigned char *font_glyph(char c)
{
    static const unsigned char blank[FONT_GLYPH_W] = { 0 };
    int i = (unsigned char)c - 32;
    if (i < 0 || i >= 95)
        return blank;
    return glyphs[i];
}
